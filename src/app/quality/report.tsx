"use client";

import { useEffect, useState } from "react";

type SourceCheck = {
  status: string;
  record_count?: number;
  message?: string;
  error?: string;
  tables?: Record<
    string,
    { record_count?: number; malformed_record_count?: number }
  >;
};
type Quality = {
  release_id: string;
  generated_at: string;
  pipeline_version: string;
  source_checks: Record<string, SourceCheck>;
  published_profile: {
    occupation_count: number;
    profile_rating_count: number;
    dimensions: string[];
  };
  published_transitions?: {
    cell_count: number;
    respondent_count: number;
    uncertainty_status: string;
    weight_variable: string;
  } | null;
};
const api = (
  process.env.NEXT_PUBLIC_API_URL ?? "http://localhost:8000/api/v1"
).replace(/\/$/, "");

const sourceTitles: Record<string, string> = {
  cps_dwjt_2026: "U.S. Census Bureau · CPS (Jan 2026)",
  onet_31_0: "USDOL / O*NET Development · O*NET 31.0",
  bls_projections_2025_2035: "U.S. BLS · Employment Projections (2025–2035)",
};
const dimensionTitles: Record<string, string> = {
  essential_skills: "Essential skills",
  transferable_skills: "Transferable skills",
  work_activities: "Work activities",
  work_context: "Work context",
};

export function QualityReport() {
  const [report, setReport] = useState<Quality | null>(null);
  const [error, setError] = useState("");

  useEffect(() => {
    fetch(`${api}/quality`)
      .then(async (response) => {
        const body = await response.json();
        if (!response.ok)
          throw new Error(
            body?.detail?.message ?? "Quality report is unavailable.",
          );
        setReport(body);
      })
      .catch((reason) =>
        setError(
          reason instanceof Error
            ? reason.message
            : "Could not reach the quality report.",
        ),
      );
  }, []);

  if (error) {
    return (
      <div className="workspace">
        <div className="workspace-head">
          <h2>RELEASE VALIDATION</h2>
          <span className="status-pill">REPORT UNAVAILABLE</span>
        </div>
        <div className="empty-state">
          <div className="empty-icon">◌</div>
          <h3>No release quality report could be loaded.</h3>
          <p>
            {error} Start the API after running `make data-validate` and `make
            data-publish`.
          </p>
        </div>
      </div>
    );
  }
  if (!report) {
    return (
      <div className="workspace">
        <div className="workspace-head">
          <h2>RELEASE VALIDATION</h2>
          <span className="status-pill">LOADING</span>
        </div>
        <div className="empty-state">
          <h3>Loading validation results…</h3>
          <p>Results are generated by the data pipeline.</p>
        </div>
      </div>
    );
  }

  return (
    <div className="workspace">
      <div className="workspace-head">
        <h2>RELEASE VALIDATION · {report.release_id}</h2>
        <span className="status-pill">PARTIAL RELEASE</span>
      </div>
      <p className="query-message">
        Report generated {new Date(report.generated_at).toLocaleString()} ·
        Pipeline {report.pipeline_version}. Counts describe their
        source-specific validation stages and are not directly comparable.
      </p>
      <div className="quality-grid">
        {Object.entries(report.source_checks).map(([id, source]) => (
          <article className="info-card" key={id}>
            <span
              className={`quality-status ${source.status.includes("failed") ? "failed" : ""}`}
            >
              {source.status.replaceAll("_", " ")}
            </span>
            <h3>{sourceTitles[id] ?? id.replaceAll("_", " ")}</h3>
            {source.record_count != null && (
              <p>
                <b>{source.record_count.toLocaleString()}</b>{" "}
                {id.startsWith("cps")
                  ? "physical input records (not eligible respondents)"
                  : "source records"}
              </p>
            )}
            {source.tables && (
              <p>
                {Object.keys(source.tables).length} tables inspected ·{" "}
                {Object.values(source.tables)
                  .reduce(
                    (total, table) => total + (table.record_count ?? 0),
                    0,
                  )
                  .toLocaleString()}{" "}
                rows across source tables
              </p>
            )}
            {source.message && <p>{source.message}</p>}
            {source.error && <p className="error-text">{source.error}</p>}
          </article>
        ))}
      </div>
      <div className="quality-profile">
        <h3>Published O*NET occupational profiles</h3>
        <p>
          {report.published_profile.occupation_count.toLocaleString()}{" "}
          occupations ·{" "}
          {report.published_profile.profile_rating_count.toLocaleString()}{" "}
          ratings across{" "}
          {report.published_profile.dimensions
            .map((d) => dimensionTitles[d] ?? d.replaceAll("_", " "))
            .join(", ")}
          .
        </p>
        <p>
          These records describe occupational profiles; they are not worker
          transition estimates.
        </p>
      </div>
      {report.published_transitions && (
        <div className="quality-profile">
          <h3>Published CPS transition estimates</h3>
          <p>
            {report.published_transitions.cell_count.toLocaleString()}{" "}
            occupation-pair cells from{" "}
            {report.published_transitions.respondent_count.toLocaleString()}{" "}
            valid responses · Weight:{" "}
            {report.published_transitions.weight_variable}.
          </p>
          <p>
            Uncertainty status:{" "}
            {report.published_transitions.uncertainty_status ===
            "unavailable_replicate_weight_archive_not_downloaded"
              ? "Unavailable (replicate-weight archive not downloaded)"
              : report.published_transitions.uncertainty_status.replaceAll(
                  "_",
                  " ",
                )}
            . Confidence intervals are not available in this release.
          </p>
        </div>
      )}
    </div>
  );
}
